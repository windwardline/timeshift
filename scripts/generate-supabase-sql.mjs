// Generates docs/supabase-lockdown.sql — everything the two Supabase projects need,
// as one script that can be pasted into the dashboard's SQL Editor. For the case
// where the person applying the fix has no clone, no Node, and no connection
// string, only a browser and the dashboard.
//
// Generated from the migration files themselves so the SQL and the recorded
// checksums cannot drift from what `prisma migrate deploy` would apply:
//   node scripts/generate-supabase-sql.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const MIGRATIONS = [
  '20260818204500_lock_down_public_schema',
  '20260818211531_add_rate_limit',
  '20260818212336_drop_dead_password_hash',
];

// The lockdown migration is already guarded and idempotent. The other two are
// plain generated DDL, so they get re-run safety here rather than in the
// migration, where `migrate deploy` guarantees once-only application anyway.
const IDEMPOTENT = {
  '20260818211531_add_rate_limit': (sql) =>
    sql
      .replace('CREATE TABLE "RateLimit"', 'CREATE TABLE IF NOT EXISTS "RateLimit"')
      .replace('CREATE INDEX "RateLimit_expiresAt_idx"', 'CREATE INDEX IF NOT EXISTS "RateLimit_expiresAt_idx"'),
  '20260818212336_drop_dead_password_hash': (sql) =>
    sql.replace('DROP COLUMN "passwordHash"', 'DROP COLUMN IF EXISTS "passwordHash"'),
};

const parts = [];
parts.push(`-- TimeShift: close the public-schema exposure on this Supabase project.
--
-- Paste this whole file into the SQL Editor and run it. Safe to run twice, and
-- safe to run on a project that is already fixed. Everything is in one
-- transaction: if any statement fails, nothing is applied.
--
-- Generated by scripts/generate-supabase-sql.mjs from the migrations themselves.
-- It applies exactly what \`prisma migrate deploy\` would, and records the same
-- migration history, so the CLI stays consistent with the database afterwards.

BEGIN;
`);

for (const name of MIGRATIONS) {
  const path = join('prisma/migrations', name, 'migration.sql');
  const raw = readFileSync(path, 'utf8');
  const checksum = createHash('sha256').update(raw).digest('hex'); // what Prisma stores
  const body = (IDEMPOTENT[name] ?? ((s) => s))(raw);

  parts.push(`
-- ===========================================================================
-- ${name}
-- ===========================================================================
${body.trim()}

-- Record it the way \`prisma migrate deploy\` would, so the CLI does not try to
-- apply it again later.
INSERT INTO "_prisma_migrations"
  ("id", "checksum", "finished_at", "migration_name", "logs", "rolled_back_at", "started_at", "applied_steps_count")
SELECT gen_random_uuid()::text, '${checksum}', now(), '${name}', NULL, NULL, now(), 1
WHERE NOT EXISTS (
  SELECT 1 FROM "_prisma_migrations" WHERE "migration_name" = '${name}'
);
`);
}

parts.push(`
-- ===========================================================================
-- Rotate the credentials the exposure made readable
-- ===========================================================================
-- Session tokens and unconsumed magic links were readable by anyone holding this
-- project's publishable key, and both are bearer credentials with no second
-- factor. Expiring rather than deleting keeps the history and is safe to repeat.
-- Everyone signs in again as normal.
UPDATE "Session"    SET "expiresAt" = now() WHERE "expiresAt" > now();
UPDATE "LoginToken" SET "usedAt"    = now() WHERE "usedAt" IS NULL;

COMMIT;

-- ===========================================================================
-- Verification — every row must read: rls = true, anon = false, authenticated = false
-- ===========================================================================
SELECT c.relname                                                     AS "table",
       c.relrowsecurity                                              AS "rls",
       COALESCE(has_table_privilege('anon',          c.oid, 'SELECT'), false) AS "anon_can_read",
       COALESCE(has_table_privilege('authenticated', c.oid, 'SELECT'), false) AS "authenticated_can_read"
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r'
ORDER BY 1;
`);

writeFileSync('docs/supabase-lockdown.sql', parts.join('\n'));
console.log('wrote docs/supabase-lockdown.sql');
