// Generates docs/supabase-lockdown.sql — everything the two Supabase projects need,
// as one script that can be pasted into the dashboard's SQL Editor. For the case
// where the person applying the fix has no clone, no Node, and no connection
// string, only a browser and the dashboard.
//
// Generated from the migration files themselves so the SQL and the recorded
// checksums cannot drift from what `prisma migrate deploy` would apply:
//   node scripts/generate-supabase-sql.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { lockdownMigrations } from './lockdown-migrations.mjs';

const MIGRATIONS = lockdownMigrations();

// The lockdown migration is already guarded and idempotent. The other two are
// plain generated DDL, so they get re-run safety here rather than in the
// migration, where `migrate deploy` guarantees once-only application anyway.
// Each entry is (needle -> replacement). Applied strictly: a needle that no longer
// matches throws rather than no-opping, because a silent miss costs the file its
// safe-to-run-twice property and the failure only shows up as an aborted
// transaction on someone's second paste.
const IDEMPOTENT = {
  '20260818211531_add_rate_limit': [
    ['CREATE TABLE "RateLimit"', 'CREATE TABLE IF NOT EXISTS "RateLimit"'],
    ['CREATE INDEX "RateLimit_expiresAt_idx"', 'CREATE INDEX IF NOT EXISTS "RateLimit_expiresAt_idx"'],
  ],
  '20260818212336_drop_dead_password_hash': [
    ['DROP COLUMN "passwordHash"', 'DROP COLUMN IF EXISTS "passwordHash"'],
  ],
};

function makeIdempotent(name, sql) {
  let out = sql;
  for (const [needle, replacement] of IDEMPOTENT[name] ?? []) {
    if (!out.includes(needle)) {
      throw new Error(
        `${name}: expected to make ${JSON.stringify(needle)} re-runnable, but it is not in the ` +
          'migration any more. Update IDEMPOTENT rather than shipping a file that aborts on a second run.',
      );
    }
    out = out.replace(needle, replacement);
  }
  return out;
}

const parts = [];
parts.push(`-- TimeShift: close the public-schema exposure on this Supabase project.
--
-- Paste this whole file into the SQL Editor and run it. Safe to run twice, and
-- safe to run on a project that is already fixed. Everything is in one
-- transaction: if any statement fails, nothing is applied.
--
-- Generated by scripts/generate-supabase-sql.mjs from the migrations themselves.
-- It applies exactly what \`prisma migrate deploy\` would, and records the same
-- migration history, so the CLI stays consistent with the database afterwards.

BEGIN;

-- Precondition. This file carries the lockdown migrations only, not the whole
-- schema, so it assumes the project has already been migrated up to that point.
-- Without this check the first ALTER TABLE fails, every following statement
-- reports "current transaction is aborted", and the operator has to read a wall
-- of cascade noise to find the one sentence that matters. Nothing is applied
-- either way -- the transaction is what guarantees that -- this just says why.
DO $$
BEGIN
  IF to_regclass('public."User"') IS NULL THEN
    RAISE EXCEPTION 'This project has no TimeShift schema yet, so there is nothing to lock down. This file carries the lockdown migrations only. Apply the earlier migrations first (prisma migrate deploy), then run this again. Nothing has been changed.';
  END IF;
END
$$;
`);

for (const name of MIGRATIONS) {
  const path = join('prisma/migrations', name, 'migration.sql');
  const raw = readFileSync(path, 'utf8');
  const checksum = createHash('sha256').update(raw).digest('hex'); // what Prisma stores
  const body = makeIdempotent(name, raw);

  parts.push(`
-- ===========================================================================
-- ${name}
-- ===========================================================================
${body.trim()}

-- Record it the way \`prisma migrate deploy\` would, so the CLI does not try to
-- apply it again later.
INSERT INTO "_prisma_migrations"
  ("id", "checksum", "finished_at", "migration_name", "logs", "rolled_back_at", "started_at", "applied_steps_count")
SELECT gen_random_uuid()::text, '${checksum}', now(), '${name}', NULL, NULL, now(), 1
WHERE NOT EXISTS (
  SELECT 1 FROM "_prisma_migrations" WHERE "migration_name" = '${name}'
);
`);
}

parts.push(`
-- ===========================================================================
-- Rotate the credentials the exposure made readable
-- ===========================================================================
-- Session tokens and unconsumed magic links were readable by anyone holding this
-- project's publishable key, and both are bearer credentials with no second
-- factor. Expiring rather than deleting keeps the history and is safe to repeat.
-- Everyone signs in again as normal.
UPDATE "Session"    SET "expiresAt" = now() WHERE "expiresAt" > now();
UPDATE "LoginToken" SET "usedAt"    = now() WHERE "usedAt" IS NULL;

COMMIT;

-- ===========================================================================
-- Verification -- one query, one result grid, every row must say OK
-- ===========================================================================
-- The SQL Editor only renders the LAST statement's results, so the whole verdict
-- is folded into a single query rather than split across two.
--
-- Row 1 covers what exists today, checked across the same surface the migration
-- revokes -- all four read/write privileges, and views, materialized views and
-- sequences as well as tables -- because a role holding only INSERT, or a view
-- over "User", is exposure a SELECT-on-tables check reports as clean.
--
-- The remaining rows cover the half that regresses silently: default privileges
-- decide what the NEXT object created gets, whatever today's objects say. There
-- is one row per (role, object class), so several are normal. A default-ACL entry
-- only governs objects created by its owner, so Supabase's own internal entries
-- are expected and harmless -- they never govern an object your migrations make.
-- These rows may be absent entirely, which is also fine: a one-row grid saying OK
-- is a pass, not a truncated result.
WITH obj AS (
  SELECT CASE WHEN c.relkind IN ('r','p') AND NOT c.relrowsecurity THEN false ELSE true END AS rls_ok,
         NOT (COALESCE(has_table_privilege('anon', c.oid, 'SELECT'), false)
           OR COALESCE(has_table_privilege('anon', c.oid, 'INSERT'), false)
           OR COALESCE(has_table_privilege('anon', c.oid, 'UPDATE'), false)
           OR COALESCE(has_table_privilege('anon', c.oid, 'DELETE'), false)
           OR COALESCE(has_table_privilege('authenticated', c.oid, 'SELECT'), false)
           OR COALESCE(has_table_privilege('authenticated', c.oid, 'INSERT'), false)
           OR COALESCE(has_table_privilege('authenticated', c.oid, 'UPDATE'), false)
           OR COALESCE(has_table_privilege('authenticated', c.oid, 'DELETE'), false)) AS no_api_access
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r','p','v','m','f','S')
)
SELECT 1                                                       AS ord,
       'existing objects'                                      AS "check",
       count(*)::text || ' object(s) in public'                AS detail,
       CASE WHEN count(*) FILTER (WHERE NOT no_api_access) > 0
              THEN 'PROBLEM - ' || count(*) FILTER (WHERE NOT no_api_access)::text
                   || ' reachable with the publishable key'
            WHEN count(*) FILTER (WHERE NOT rls_ok) > 0
              THEN 'PROBLEM - ' || count(*) FILTER (WHERE NOT rls_ok)::text
                   || ' table(s) without RLS'
            ELSE 'OK' END                                      AS verdict
FROM obj
UNION ALL
SELECT 2,
       'future objects',
       'default privileges on ' || CASE d.defaclobjtype
              WHEN 'r' THEN 'tables'    WHEN 'S' THEN 'sequences'
              WHEN 'f' THEN 'functions' WHEN 'T' THEN 'types'
              ELSE d.defaclobjtype::text END
         || ' owned by ' || pg_get_userbyid(d.defaclrole)
         || ' grant ' || string_agg(DISTINCT r.rolname, ' + '),
       CASE WHEN pg_get_userbyid(d.defaclrole) = current_user
            THEN 'PROBLEM - governs the objects your migrations create'
            ELSE 'OK - Supabase internal role, never governs your objects' END
FROM pg_default_acl d
JOIN pg_namespace n ON n.oid = d.defaclnamespace
CROSS JOIN LATERAL aclexplode(d.defaclacl) a
JOIN pg_roles r ON r.oid = a.grantee
WHERE n.nspname = 'public' AND r.rolname IN ('anon', 'authenticated')
GROUP BY d.defaclrole, d.defaclobjtype
ORDER BY 1;
`);

// `--out <path>` so a caller can generate somewhere else -- the drift test needs
// to compare against a fresh render WITHOUT rewriting the committed artifact,
// which would let the test quietly repair the very drift it exists to catch.
const outFlag = process.argv.indexOf('--out');
if (outFlag !== -1 && !process.argv[outFlag + 1]) {
  console.error('--out needs a path');
  process.exit(2);
}
const OUT = outFlag === -1 ? 'docs/supabase-lockdown.sql' : process.argv[outFlag + 1];

writeFileSync(OUT, parts.join('\n'));
console.log(`wrote ${OUT}`);
